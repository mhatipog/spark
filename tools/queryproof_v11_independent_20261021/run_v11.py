from rank_ast import decode
from guard_binding_v11 import observe, Rejected, LOGICAL, EXPR

def mutations(event):
    def changed_join_operator(newclass):
        variant=copy.deepcopy(event)
        for side in ("old","new"):
            matches=[n for n in variant[side]
                     if isinstance(n,dict) and n.get("class")==LOGICAL+"Join"]
            if len(matches)!=1:
                raise RuntimeError("NONUNIQUE_JOIN_MUTANT")
            matches[0]["condition"][0]["class"]=EXPR+newclass
        return variant
    altered=copy.deepcopy(event)
    filters=[n for n in altered["new"]
             if isinstance(n,dict) and n.get("class")==LOGICAL+"Filter" and
             isinstance(n.get("condition"),list) and
             len(n["condition"])==2 and
             isinstance(n["condition"][0],dict) and
             n["condition"][0].get("class")==EXPR+"IsNotNull"]
    if not filters:
        raise RuntimeError("GUARD_EXPECTED_IN_LIVE_CATALYST_EVENT")
    filters[0]["condition"][1]["exprId"]["id"] += 1000000
    return {
        "nullsafe_comparison":changed_join_operator("EqualNullSafe"),
        "or_substitution":changed_join_operator("Or"),
        "foreign_expr_id":altered,
    }

def score_v11(path):
    report=run_v10.score_v10(path)
    reference=report["v10_coq_guard_witnesses"]["witnesses"]
    observed=[]
    checks=[]
    for line in path.read_text(errors="replace").splitlines():
        if not line.startswith("QUERYPROOF_AST\t"):
            continue
        event=decode(line)
        if event["case"] not in run_v10.TARGETS or event["old"]==event["new"]:
            continue
        expected=run_v10.parse_witness(event)
        if expected is None:
            continue
        independently=observe(event)
        if independently != expected:
            raise RuntimeError("INDEPENDENT_CATALYST_BINDING_DISAGREEMENT")
        observed.append(independently)
        for label, variant in mutations(event).items():
            try:
                observe(variant)
            except Rejected as exc:
                checks.append({"case":event["case"],"mutant":label,
                               "rejection":str(exc)})
            else:
                raise RuntimeError("INDEPENDENT_BINDING_MUTANT_ACCEPTED_"+label)
    if observed != reference:
        raise RuntimeError("V11_COQ_INSTANCES_DO_NOT_MATCH_INDEPENDENT_OBSERVER")
    if len(observed)<4 or len(checks)!=3*len(observed):
        raise RuntimeError("V11_INCOMPLETE_ADVERSARIAL_CONTROLS")
    report["v11_independent_ast_binding"]={
        "status":"POSTHOC_INDEPENDENT_REFLECTION_CHECKED",
        "observed_case_ids":sorted({w["case"] for w in observed}),
        "independent_witness_count":len(observed),
        "negative_mutant_rejections":len(checks),
        "negative_mutants":checks,
        "limits":[
            "Both parsers run in Python and are not verified by Coq",
            "TreeNode.toJSON omits native metadata and hidden cache state",
            "Semantic proof is restricted to nullable signed integer join keys",
            "No prospective W32 performance claim, and original X strict 0/16 stands",
        ]
    }
    return report

run_external.union_coverage=score_v11
run_external.OUTPUT=ROOT/"artifacts/queryproof_v11_w32_independent_coq_guard.json"

